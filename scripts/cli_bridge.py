#!/usr/bin/env python3
"""
Nerdbot CLI Bridge & Session Replay Utility
Enables terminal commands, Master Control daemons, and personal agents (Hermes, SAO, Eve)
to interact with authenticated browser sessions and execute automated tasks.
"""

import argparse
import json
import os
import shlex
import subprocess
import sys
import urllib.request
import urllib.error

DEFAULT_AGENTS = {
    "hermes-legion": "http://localhost:8000/v1",
    "hermes-nukbox": "http://nukbox.local:8000/v1",
    "hermes-spine": "http://spine.local:8000/v1",
    "sao-core": "http://localhost:4177/v1",
    "openclaw": "http://localhost:18789/v1",
}

ARCHITECT_APPCTL = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "the-architect", "appctl", "appctl.py")
)
DEFAULT_COOKIE_FILE = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "..", "..", "sockmusegoogle.json")
)

def check_agent(name: str, url: str) -> bool:
    models_url = f"{url.rstrip('/')}/models"
    try:
        req = urllib.request.Request(models_url, headers={"User-Agent": "Nerdbot-CLI/1.0"})
        with urllib.request.urlopen(req, timeout=3) as resp:
            data = json.loads(resp.read().decode())
            models = [m.get("id") for m in data.get("data", [])] if "data" in data else []
            print(f"  [ONLINE] {name} ({url}) -> Models: {', '.join(models[:3]) or 'ok'}")
            return True
    except Exception as e:
        print(f"  [OFFLINE] {name} ({url}) -> {e}")
        return False

def ping_fleet():
    print("\n--- Pinging Personal Agent Fleet ---")
    online = 0
    for name, url in DEFAULT_AGENTS.items():
        if check_agent(name, url):
            online += 1
    print(f"\nResult: {online}/{len(DEFAULT_AGENTS)} agent nodes reachable.\n")

def replay_session_request(curl_command: str):
    """Executes a replay request generated by Nerdbot's browser_extract_session tool safely across OSes."""
    cleaned_lines = []
    for line in curl_command.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        if s.endswith("\\"):
            s = s[:-1].strip()
        cleaned_lines.append(s)
    normalized_cmd = " ".join(cleaned_lines)
    if not normalized_cmd:
        print("Error: Empty replay command.", file=sys.stderr)
        return
    print(f"Executing authenticated session replay:\n  {normalized_cmd}")
    args = shlex.split(normalized_cmd, posix=True)
    if args and args[0].lower() == "curl":
        args[0] = "curl.exe" if sys.platform == "win32" else "curl"
    res = subprocess.run(args, check=False)
    if res.returncode != 0:
        sys.exit(res.returncode)


def run_architect_browser(action: str, url: str = None, cookie_file: str = None, worker_id: str = "all", headless: bool = True):
    """Bridge Nerdbot CLI directly into The Architect's Unified Browser & Ephemeral Worker system."""
    if not os.path.isfile(ARCHITECT_APPCTL):
        print(f"Error: Architect appctl not found at {ARCHITECT_APPCTL}", file=sys.stderr)
        sys.exit(1)

    cmd = [sys.executable, ARCHITECT_APPCTL, "browser", action]
    if action in ("fork", "bridge"):
        if url:
            cmd.extend(["--url", url])
        cfile = cookie_file or (DEFAULT_COOKIE_FILE if os.path.isfile(DEFAULT_COOKIE_FILE) else None)
        if cfile:
            cmd.extend(["--cookie-file", cfile])
        if headless:
            cmd.append("--headless")
    elif action == "destroy":
        cmd.append(worker_id or "all")

    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.stdout:
        print(res.stdout.strip())
    if res.stderr:
        print(res.stderr.strip(), file=sys.stderr)
    if res.returncode != 0:
        sys.exit(res.returncode)


def main():
    parser = argparse.ArgumentParser(description="Nerdbot CLI & Session Bridge")
    subparsers = parser.add_subparsers(dest="command")

    # Fleet ping
    subparsers.add_parser("fleet", help="Ping all configured personal agent nodes")

    # Dispatch to agent
    ask_parser = subparsers.add_parser("ask", help="Send prompt to a personal agent node")
    ask_parser.add_argument("prompt", help="Prompt or task for the agent")
    ask_parser.add_argument("--agent", default="hermes-legion", choices=list(DEFAULT_AGENTS.keys()), help="Target agent")
    ask_parser.add_argument("--model", default="default", help="Model ID")

    # Replay session
    replay_parser = subparsers.add_parser("replay", help="Execute an authenticated cURL command from Nerdbot")
    replay_parser.add_argument("curl_file_or_string", help="cURL command string or file path")

    # Architect Unified Browser Bridge
    browser_parser = subparsers.add_parser("browser", help="Control Unified SAO Browser & Ephemeral Workers via The Architect")
    browser_parser.add_argument(
        "action",
        choices=["status", "url", "fork", "bridge", "list", "destroy", "takeover", "resume"],
        help="Browser action to execute",
    )
    browser_parser.add_argument("--url", default=None, help="Target URL for fork/bridge")
    browser_parser.add_argument("--cookie-file", default=None, help="Cookie JSON file to inject")
    browser_parser.add_argument("--worker-id", default="all", help="Worker ID or 'all' for destroy")
    browser_parser.add_argument("--visible", action="store_true", help="Run visible browser window instead of headless")

    args = parser.parse_args()

    if args.command == "fleet":
        ping_fleet()
    elif args.command == "replay":
        cmd = args.curl_file_or_string
        if os.path.exists(cmd):
            with open(cmd, "r", encoding="utf-8") as f:
                cmd = f.read()
        replay_session_request(cmd)
    elif args.command == "browser":
        run_architect_browser(
            action=args.action,
            url=args.url,
            cookie_file=args.cookie_file,
            worker_id=args.worker_id,
            headless=not args.visible,
        )
    elif args.command == "ask":
        base_url = DEFAULT_AGENTS.get(args.agent, "http://localhost:8000/v1")
        url = f"{base_url.rstrip('/')}/chat/completions"
        payload = {
            "model": args.model,
            "messages": [{"role": "user", "content": args.prompt}],
            "temperature": 0.7,
        }
        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json", "User-Agent": "Nerdbot-CLI/1.0"},
            )
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read().decode())
                reply = data["choices"][0]["message"]["content"]
                print(f"\n[{args.agent}]:\n{reply}\n")
        except Exception as e:
            print(f"Error querying {args.agent}: {e}", file=sys.stderr)
    else:
        parser.print_help()

if __name__ == "__main__":
    main()
